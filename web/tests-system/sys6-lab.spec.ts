import { test, expect, type Page } from '@playwright/test';
import { staffLogin, password, suffix } from './helpers';
test.beforeAll(() => { if (!password) throw new Error('Set E2E_DEMO_PASSWORD'); });
const pick = async (page: Page, sel: ReturnType<Page['locator']>) => { await sel.click(); await page.waitForTimeout(400); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter'); };

test('SYS6-04/07 plan row menu and lab order', async ({ page }) => {
  const work = `Mão sứ ${suffix()}`;
  await staffLogin(page, 'dentist.demo');
  await page.goto('/patients/38');
  await page.getByRole('tab', { name: 'Điều trị & Thanh toán' }).click(); await page.waitForTimeout(2000);
  const n = await page.getByText('Ngày lập phiếu').count();
  await page.getByRole('button', { name: /tạo phiếu mới/i }).click();
  await expect(page.getByText('Ngày lập phiếu')).toHaveCount(n + 1);
  const pt = page.locator('table').filter({ hasText: 'Thời gian dự kiến' }).first();
  await pt.getByRole('columnheader').getByRole('button').first().click();
  await pt.getByPlaceholder('25, 26, 46').fill('16');
  await pick(page, pt.locator('.ant-select').first());
  await pt.getByRole('button', { name: 'Đồng ý' }).click();
  await expect(page.getByText(/Tổng dự toán: 300\.000/)).toBeVisible();
  await page.getByRole('button', { name: '⋯' }).first().click({ timeout: 5000 }).catch(() => console.log('NO_MORE_BTN'));
  await page.waitForTimeout(800);
  console.log('PLANMENU', JSON.stringify(await page.locator('.ant-dropdown:visible, .ant-popover:visible, [role=menu]').allInnerTexts()));
  await page.screenshot({ path: 'test-results/sys6-04.png', fullPage: true });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Thêm quá trình điều trị' }).first().click();
  const wt = page.locator('table').filter({ hasText: 'Labo' }).first();
  await wt.getByPlaceholder('25, 26, 46').fill('16');
  await pick(page, wt.locator('.ant-select').first());
  await wt.getByRole('button', { name: 'Đồng ý' }).click();
  await page.waitForTimeout(2500);
  await page.getByRole('button', { name: /Phiếu labo cho/ }).first().click();
  const d = page.getByRole('dialog');
  await d.getByLabel('Công việc labo', { exact: true }).fill(work);
  await d.getByRole('button', { name: 'Răng 16' }).click();
  await d.getByLabel('Tổng phí').fill('500000');
  await d.getByRole('button', { name: 'LƯU LẠI' }).click();
  await page.waitForTimeout(3000);
  await page.screenshot({ path: 'test-results/sys6-07a.png' });
  console.log('LEFT', await page.getByRole('dialog').count());
  await page.getByRole('link', { name: 'Quản lý công việc labo', exact: true }).click();
  await page.waitForTimeout(4000);
  console.log('LABLIST', (await page.locator('#staff-content').innerText()).includes(work));
});
