        public Task<DCMS.Application.Features.Settings.PermissionState> ResolveAsync(int actorId, CancellationToken ct) => Task.FromResult(State);
        public Task<DCMS.Application.Features.Settings.PermissionState> RequireAsync(int actorId, string permission, CancellationToken ct) => Task.FromResult(State);
        public Task OperationalAsync(int actorId, string permission, int branchId, CancellationToken ct) => Task.CompletedTask;
    }

    /// <summary>Runs the action and returns the BusinessException it throws (fails the test if none).</summary>
    public static async Task<BusinessException> ErrorOf(Func<Task> action)
    {
        var failure = await Record.ExceptionAsync(action);
        Assert.NotNull(failure);
        if (failure is not BusinessException business) throw new Xunit.Sdk.XunitException("Expected BusinessException but got: " + failure);
        return business;
    }
