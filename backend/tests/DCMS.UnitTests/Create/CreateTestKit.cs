    public static DcmsDbContext NewDb() => new(new DbContextOptionsBuilder<DcmsDbContext>()
        .UseInMemoryDatabase(Guid.NewGuid().ToString())
        .ConfigureWarnings(w => w.Ignore(InMemoryEventId.TransactionIgnoredWarning)).Options);

    /// <summary>
    /// SQLite database for services that run Postgres-only SQL (advisory lock) or transactions; the lock call is
    /// replaced by a no-op SQL function so the real code path (validation after the lock) can run.
    /// </summary>
    public static DcmsDbContext NewSqliteDb()
    {
        var connection = new Microsoft.Data.Sqlite.SqliteConnection("Data Source=:memory:");
        connection.Open();
        connection.CreateFunction("pg_advisory_xact_lock", (long _) => 0L);
        // Postgres functions used by column defaults / computed columns / constraints in the model.
        connection.CreateFunction<object?, string?, string?>("btrim", null, (_, s) => s?.Trim(), true);
        connection.CreateFunction<object?, string?, string?, string?>("btrim", null, (_, s, c) => s?.Trim((c ?? " ").ToCharArray()), true);
        connection.CreateFunction<object?, string?, string?, string?, string?>("regexp_replace", null, (_, s, p, r) =>
            s == null ? null : System.Text.RegularExpressions.Regex.Replace(s, p ?? "", r ?? ""), true);
        connection.CreateFunction<object?, string?, string?, string?, string?, string?>("regexp_replace", null, (_, s, p, r, f) =>
            s == null ? null : System.Text.RegularExpressions.Regex.Replace(s, p ?? "", r ?? ""), true);
        // SQLite's built-in upper() only folds ASCII; PostgreSQL folds Vietnamese letters too (case-insensitive duplicate checks).
        connection.CreateFunction<string?, string?>("upper", s => s?.ToUpperInvariant(), true);
        long counter = 0;
        connection.CreateFunction("nextval", (string? _) => ++counter);
        var db = new DcmsDbContext(new DbContextOptionsBuilder<DcmsDbContext>().UseSqlite(connection)
            .ReplaceService<Microsoft.EntityFrameworkCore.Infrastructure.IModelCustomizer, WithoutSequences>().Options);
        db.Database.EnsureCreated();
        return db;
    }

    /// <summary>SQLite has no sequences; drop them from the model (only needed to create the tables).</summary>
    private sealed class WithoutSequences(Microsoft.EntityFrameworkCore.Infrastructure.ModelCustomizerDependencies dependencies)
        : Microsoft.EntityFrameworkCore.Infrastructure.ModelCustomizer(dependencies)
    {
        public override void Customize(ModelBuilder modelBuilder, DbContext context)
        {
            base.Customize(modelBuilder, context);
            foreach (var sequence in modelBuilder.Model.GetSequences().ToList())
                modelBuilder.Model.RemoveSequence(sequence.Name, sequence.ModelSchema);
            // Postgres casts in column defaults ('{}'::jsonb) are not valid SQLite; keep the literal.
            foreach (var property in modelBuilder.Model.GetEntityTypes().SelectMany(e => e.GetProperties()))
                if (property.GetDefaultValueSql() is { } sql && sql.Contains("::jsonb"))
                    property.SetDefaultValueSql(sql.Replace("::jsonb", ""));
            // Postgres' xmin system column is generated by the server; SQLite needs a default so inserts succeed.
            foreach (var property in modelBuilder.Model.GetEntityTypes().SelectMany(e => e.GetProperties()))
                if (property.GetColumnName() == "xmin") property.SetDefaultValueSql("0");
        }
    }

    public static UserManager<ApplicationUser> NewUserManager(DcmsDbContext db)
    {
        var services = new ServiceCollection();
        services.AddLogging();
        services.AddSingleton(db);
        services.AddIdentityCore<ApplicationUser>(options =>
            options.User.AllowedUserNameCharacters = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-._")
            .AddRoles<IdentityRole<int>>().AddEntityFrameworkStores<DcmsDbContext>();
        return services.BuildServiceProvider().GetRequiredService<UserManager<ApplicationUser>>();
    }

    /// <summary>A DbContext on the shared test schema; disposing it only closes the context.</summary>
    public sealed class PostgresDb(DcmsDbContext db) : IAsyncDisposable
    {
        public DcmsDbContext Db { get; } = db;
        public ValueTask DisposeAsync() => Db.DisposeAsync();
    }

    private static int nextId = 1000;
    /// <summary>Unique number per call, so tests sharing the Postgres schema never collide on branch ids, user names or codes.</summary>
    public static int NextId() => Interlocked.Increment(ref nextId);

    private static readonly SemaphoreSlim PostgresLock = new(1, 1);
    private static (string Admin, string Scoped, string Schema)? postgres;

    /// <summary>
    /// Real PostgreSQL (the development server from ConnectionStrings__DefaultConnection) in ONE throw-away schema per test run,
    /// migrated once and dropped by PostgresCollection when the Postgres tests finish; the same approach the integration tests use. Needed for code that takes
    /// pg_advisory_xact_lock or queries JSON collections, which InMemory and SQLite cannot run.
    /// </summary>
    public static async Task DropPostgresSchemaAsync()
    {
        if (postgres is not { } p) return;
        await using var connection = new Npgsql.NpgsqlConnection(p.Admin);
        await connection.OpenAsync();
        await using var command = new Npgsql.NpgsqlCommand($"DROP SCHEMA \"{p.Schema}\" CASCADE", connection);
        await command.ExecuteNonQueryAsync();
        postgres = null;
    }

    public static async Task<PostgresDb> NewPostgresDbAsync()
    {
        await PostgresLock.WaitAsync();
        try
        {
            if (postgres is null)
            {
                var admin = Environment.GetEnvironmentVariable("ConnectionStrings__DefaultConnection")
                    ?? throw new InvalidOperationException("Run infrastructure/scripts/import-development-env.ps1 first: these tests need the PostgreSQL server.");
                var schema = "dcms_unit_" + Guid.NewGuid().ToString("N");
                await using (var connection = new Npgsql.NpgsqlConnection(admin))
                {
                    await connection.OpenAsync();
                    await using var command = new Npgsql.NpgsqlCommand($"CREATE SCHEMA \"{schema}\"", connection);
                    await command.ExecuteNonQueryAsync();
                }
                var scoped = new Npgsql.NpgsqlConnectionStringBuilder(admin) { SearchPath = schema }.ConnectionString;
                await using (var migrating = new DcmsDbContext(new DbContextOptionsBuilder<DcmsDbContext>().UseNpgsql(scoped).Options))
                    await migrating.Database.MigrateAsync();
                postgres = (admin, scoped, schema);
            }
        }
        finally { PostgresLock.Release(); }
        return new(new DcmsDbContext(new DbContextOptionsBuilder<DcmsDbContext>().UseNpgsql(postgres.Value.Scoped).Options));
    }

    /// <summary>UserManager on the project's own AccountUserStore (roles are read from ApplicationUser.AssignedRoles).</summary>
    public static UserManager<ApplicationUser> NewRoleUserManager(DcmsDbContext db)
    {
        var services = new ServiceCollection();
        services.AddLogging();
        services.AddSingleton(db);
        services.AddIdentityCore<ApplicationUser>().AddRoles<IdentityRole<int>>().AddUserStore<AccountUserStore>();
        return services.BuildServiceProvider().GetRequiredService<UserManager<ApplicationUser>>();
    }

    /// <summary>Adds a branch, a staff account holding the role, and (when canDentist) membership of the branch as a dentist.</summary>
    public static async Task<ApplicationUser> SeedStaffAsync(DcmsDbContext db, string userName, string role, int branchId, bool member = true)
    {
        var branch = await db.Set<DCMS.Domain.Features.Scheduling.SchedulingBranch>().SingleOrDefaultAsync(x => x.Id == branchId);
        if (branch == null)
            db.Set<DCMS.Domain.Features.Scheduling.SchedulingBranch>().Add(branch = new() { Id = branchId, Name = "Chi nhánh " + branchId });
        var user = new ApplicationUser { UserName = userName, FullName = userName, AccountType = "Staff", IsActive = true, AssignedRoles = [role] };
        db.Users.Add(user);
        await db.SaveChangesAsync();
        if (!member) return user; // no employee profile, so the account is not assigned to any branch
        var employee = new DCMS.Domain.Features.Accounts.EmployeeProfile { AccountId = user.Id, EmployeeCode = "NV" + user.Id, FullName = userName };
        db.Employees.Add(employee);
        await db.SaveChangesAsync();
        branch.Members.Add(new() { BranchId = branchId, EmployeeId = employee.Id, CanDentist = true, Active = true });
        await db.SaveChangesAsync();
        return user;
    }

    /// <summary>Settings access that grants every permission (the permission check itself is not under test here).</summary>
    public sealed class AllowAll : DCMS.Application.Features.Settings.ISettingsAccess
    {
